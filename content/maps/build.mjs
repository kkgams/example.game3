#!/usr/bin/env node
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

function fields(value, expected, label) {
  assert.ok(value !== null && typeof value === 'object' && !Array.isArray(value), `${label} must be an object`);
  assert.deepEqual(Object.keys(value).sort(), [...expected].sort(), `${label} must have exactly ${expected.join(', ')}`);
}

function point(value, label) {
  fields(value, ['x', 'y'], label);
  for (const axis of ['x', 'y'])
    assert.ok(typeof value[axis] === 'number' && Number.isFinite(value[axis]) && Math.abs(value[axis]) <= 32768,
      `${label}.${axis} must be a finite number within +/-32768 world pixels`);
}

/** Validate authored top-to-bottom rows and emit the shared Y-up C map. */
export function compileMap(document) {
  fields(document, ['version', 'width', 'height', 'tileSize', 'origin', 'spawn', 'collision'], 'map');
  const { version, width, height, tileSize, origin, spawn, collision } = document;
  assert.equal(version, 1, 'map.version must be 1');
  assert.equal(tileSize, 16, 'map.tileSize must be 16');
  for (const [name, value] of [['width', width], ['height', height]])
    assert.ok(Number.isInteger(value) && value >= 8 && value <= 64, `map.${name} must be an integer from 8 to 64`);
  point(origin, 'map.origin');
  point(spawn, 'map.spawn');
  assert.ok(Array.isArray(collision) && collision.length === height, 'map.collision must have exactly height rows');
  for (let row = 0; row < height; ++row) {
    assert.ok(Array.isArray(collision[row]) && collision[row].length === width, `map.collision[${row}] must have exactly width cells`);
    for (let x = 0; x < width; ++x) {
      const cell = collision[row][x];
      assert.ok(cell === 0 || cell === 1, `map.collision[${row}][${x}] must be the number 0 or 1`);
      if (row === 0 || row === height - 1 || x === 0 || x === width - 1)
        assert.equal(cell, 1, 'map must have sealed outer walls');
    }
  }
  // All following geometry uses bottom-to-top rows, matching sim_map indexing.
  const rows = [...collision].reverse();
  const cells = rows.flat();
  const first = cells.indexOf(0);
  assert.notEqual(first, -1, 'map must contain walkable cells');
  const visited = new Set([first]), queue = [first];
  for (let i = 0; i < queue.length; ++i) {
    const index = queue[i], x = index % width, y = Math.floor(index / width);
    for (const [nx, ny] of [[x - 1, y], [x + 1, y], [x, y - 1], [x, y + 1]]) {
      const next = ny * width + nx;
      if (nx >= 0 && nx < width && ny >= 0 && ny < height && cells[next] === 0 && !visited.has(next)) {
        visited.add(next);
        queue.push(next);
      }
    }
  }
  assert.equal(visited.size, cells.filter(cell => cell === 0).length, 'all walkable cells must be connected');
  let perimeter = 0;
  for (let y = 1; y < height - 1; ++y)
    for (let x = 1; x < width - 1; ++x)
      if ((x === 1 || x === width - 2 || y === 1 || y === height - 2) && rows[y][x] === 0) ++perimeter;
  assert.ok(perimeter >= 8, 'map must have at least 8 free inner-perimeter spawn cells');

  const sx = spawn.x - origin.x, sy = spawn.y - origin.y;
  assert.ok(sx - 5 >= 0 && sx + 5 <= width * tileSize && sy - 5 >= 0 && sy + 5 <= height * tileSize,
    'spawn 10x10 AABB must be inside the map');
  for (let y = 0; y < height; ++y)
    for (let x = 0; x < width; ++x)
      if (rows[y][x] === 1)
        assert.ok(sx + 5 <= x * tileSize || sx - 5 >= (x + 1) * tileSize ||
          sy + 5 <= y * tileSize || sy - 5 >= (y + 1) * tileSize, 'spawn 10x10 AABB must be clear of solid tiles');

  return [
    '/* Generated by content/maps/build.mjs; do not edit. Rows are bottom-to-top (Y-up). */',
    '#ifndef SIM_AUTHORED_MAP_H',
    '#define SIM_AUTHORED_MAP_H',
    '#include "map.h"',
    '',
    'static const uint8_t sim_authored_collision[] = {',
    ...rows.map(row => `    ${row.join(', ')},`),
    '};',
    '',
    'static const sim_map sim_authored_map = {',
    `    .width = ${width}, .height = ${height}, .tile_size = 16,`,
    `    .origin_x = ${origin.x}, .origin_y = ${origin.y},`,
    `    .spawn_x = ${spawn.x}, .spawn_y = ${spawn.y},`,
    '    .collision = sim_authored_collision,',
    '};',
    '#endif',
    '',
  ].join('\n');
}

/** Check mode validates input only; unchanged generated bytes retain their mtime. */
export async function buildMap({ input, output, checkOnly = false }) {
  assert.ok(typeof input === 'string' && input.length > 0, 'input path is required');
  assert.ok(typeof output === 'string' && output.length > 0, 'output path is required');
  assert.equal(typeof checkOnly, 'boolean', 'checkOnly must be boolean');
  const header = compileMap(JSON.parse(await readFile(input, 'utf8')));
  if (checkOnly) return header;
  let previous;
  try {
    previous = await readFile(output, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (previous !== header) {
    await mkdir(dirname(output), { recursive: true });
    await writeFile(output, header);
  }
  return header;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  assert.ok(args.length === 2 || (args.length === 3 && args[2] === '--check'),
    'usage: node content/maps/build.mjs INPUT OUTPUT [--check]');
  assert.ok(!args[0].startsWith('--') && !args[1].startsWith('--'),
    'usage: node content/maps/build.mjs INPUT OUTPUT [--check]');
  await buildMap({ input: args[0], output: args[1], checkOnly: args.length === 3 });
}
