import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readPackConfig } from './pack.mjs';

export function embedPack(bytes) {
  if (!Buffer.isBuffer(bytes) || bytes.length < 20 || !bytes.subarray(0, 4).equals(Buffer.from('RSPK')) || bytes.readUInt16LE(4) !== 1 || bytes.readUInt16LE(6) !== 1 || bytes.readUInt32LE(8) !== 16 || bytes.readUInt32LE(12) !== bytes.length - 16 || bytes.readUInt32LE(16) === 0) {
    throw new Error('invalid RSPK v1 one-slot pattern-vector header');
  }
  const lines = [];
  for (let i = 0; i < bytes.length; i += 12) lines.push(`    ${[...bytes.subarray(i, i + 12)].map(b => `0x${b.toString(16).padStart(2, '0')}`).join(', ')},`);
  return `/* Generated by content/gams/embed.mjs; do not edit. */\n#ifndef SIM_BULLETML_PACK_H\n#define SIM_BULLETML_PACK_H\n\nstatic const unsigned char sim_bulletml_pack_bytes[] = {\n${lines.join('\n')}\n};\n\n#endif\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 4) throw new Error('usage: node content/gams/embed.mjs input.rspk output.h');
  // The game binds vector index 0 to ranger: validate the same graph binding
  // even when embedding an independently built GAMS pack.
  await readPackConfig();
  const header = embedPack(await readFile(process.argv[2]));
  await mkdir(dirname(resolve(process.argv[3])), { recursive: true });
  await writeFile(process.argv[3], header);
}
